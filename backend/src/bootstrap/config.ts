import { z } from 'zod';
const schema = z.object({
  environment: z.enum(['dev', 'production']).default('dev'),
  devUserId: z
    .string()
    .regex(/^[\w-]+$/)
    .default('dev-user'),
  tableName: z.string().min(1).default('rin-dev-data'),
  assetBucketName: z.string().min(3).optional(),
  financeBucketName: z.string().min(3).optional(),
  financeImportsEnabled: z.boolean().default(false),
  assetOnboardingEnabled: z.boolean().default(false),
  assetCatalogBaseUrl: z.url().optional(),
  modelProvider: z.enum(['static', 'bedrock']).default('static'),
  // Interactive chat can use OpenAI while AWS background services keep their provider.
  agentModelProvider: z.enum(['static', 'bedrock', 'bedrock-openai', 'openai']).optional(),
  agentBedrockModelId: z.string().min(1).optional(),
  bedrockOpenAiModelId: z.string().min(1).default('us.openai.gpt-6.1-sol'),
  openAiModelId: z.string().min(1).default('gpt-6.1-sol'),
  openAiSecretArn: z.string().startsWith('arn:aws:secretsmanager:').optional(),
  openAiApiKey: z.string().min(1).optional(),
  bedrockModelId: z.string().min(1).default('amazon.nova-lite-v1:0'),
  enableDebugEndpoints: z.boolean().default(false),
  behaviorFeedbackEnabled: z.boolean().default(false),
  behaviorFeedbackFunctionArn: z.string().startsWith('arn:aws:lambda:').optional(),
  testPushEnabled: z.boolean().default(false),
  testPushDeviceId: z
    .string()
    .regex(/^[\w-]{1,128}$/)
    .default('android-test'),
  firebaseSecretArn: z.string().startsWith('arn:aws:secretsmanager:').optional(),
  cognitoIssuer: z.string().optional(),
  cognitoAudience: z.string().optional(),
  internalUserId: z.string().optional(),
  region: z.string().default('us-east-1'),
  timezone: z.string().min(1).default('America/Sao_Paulo'),
  reminderTickEnabled: z.boolean().default(false),
  proactiveTickEnabled: z.boolean().default(false),
  worldRefreshEnabled: z.boolean().default(false),
  reminderTick: z.object({
    upcomingWindowMinutes: z.coerce.number().catch(60).default(60),
    overdueNagIntervalMinutes: z.coerce.number().catch(30).default(30),
    slotWindowMinutes: z.coerce.number().catch(20).default(20),
    morningSlot: z.string().min(1).default('08:00'),
    afternoonSlot: z.string().min(1).default('13:00'),
    maxRemindersPerPush: z.coerce.number().catch(8).default(8),
  }),
  proactive: z.object({
    minCooldownMinutes: z.coerce.number().catch(180).default(180),
    maxMessagesPerDay: z.coerce.number().catch(3).default(3),
    baseChance: z.coerce.number().catch(0.1).default(0.1),
    quietHoursStart: z.string().min(1).default('23:30'),
    quietHoursEnd: z.string().min(1).default('08:00'),
  }),
});
export function loadConfig() {
  return schema.parse({
    environment: process.env.APP_ENV,
    devUserId: process.env.DEV_USER_ID,
    tableName: process.env.TABLE_NAME,
    assetBucketName: process.env.ASSET_BUCKET_NAME,
    financeBucketName: process.env.FINANCE_BUCKET_NAME,
    financeImportsEnabled: process.env.FINANCE_IMPORTS_ENABLED === 'true',
    assetOnboardingEnabled: process.env.ASSET_ONBOARDING_ENABLED === 'true',
    assetCatalogBaseUrl: process.env.ASSET_CATALOG_BASE_URL,
    modelProvider: process.env.MODEL_PROVIDER,
    agentModelProvider: process.env.AGENT_MODEL_PROVIDER,
    agentBedrockModelId: process.env.AGENT_BEDROCK_MODEL_ID,
    bedrockOpenAiModelId: process.env.BEDROCK_OPENAI_MODEL_ID,
    openAiModelId: process.env.OPENAI_MODEL_ID,
    openAiSecretArn: process.env.OPENAI_SECRET_ARN,
    openAiApiKey: process.env.OPENAI_API_KEY,
    bedrockModelId: process.env.BEDROCK_MODEL_ID,
    enableDebugEndpoints: process.env.ENABLE_DEBUG_ENDPOINTS === 'true',
    behaviorFeedbackEnabled: process.env.BEHAVIOR_FEEDBACK_ENABLED === 'true',
    behaviorFeedbackFunctionArn: process.env.BEHAVIOR_FEEDBACK_FUNCTION_ARN,
    testPushEnabled: process.env.TEST_PUSH_ENABLED === 'true',
    testPushDeviceId: process.env.TEST_PUSH_DEVICE_ID,
    firebaseSecretArn: process.env.FIREBASE_SECRET_ARN,
    cognitoIssuer: process.env.COGNITO_ISSUER,
    cognitoAudience: process.env.COGNITO_AUDIENCE,
    internalUserId: process.env.INTERNAL_USER_ID,
    region: process.env.AWS_REGION,
    timezone: process.env.TIMEZONE,
    reminderTickEnabled: process.env.REMINDER_TICK_ENABLED === 'true',
    proactiveTickEnabled: process.env.PROACTIVE_TICK_ENABLED === 'true',
    worldRefreshEnabled: process.env.WORLD_REFRESH_ENABLED === 'true',
    reminderTick: {
      upcomingWindowMinutes: process.env.UPCOMING_WINDOW_MINUTES,
      overdueNagIntervalMinutes: process.env.OVERDUE_NAG_INTERVAL_MINUTES,
      slotWindowMinutes: process.env.UNSCHEDULED_SLOT_WINDOW_MINUTES,
      morningSlot: process.env.UNSCHEDULED_MORNING_TIME,
      afternoonSlot: process.env.UNSCHEDULED_AFTERNOON_TIME,
      maxRemindersPerPush: process.env.MAX_REMINDERS_PER_PUSH,
    },
    proactive: {
      minCooldownMinutes: process.env.MIN_COOLDOWN_MINUTES,
      maxMessagesPerDay: process.env.MAX_PROACTIVE_MESSAGES_PER_DAY,
      baseChance: process.env.BASE_PROACTIVE_CHANCE,
      quietHoursStart: process.env.QUIET_HOURS_START,
      quietHoursEnd: process.env.QUIET_HOURS_END,
    },
  });
}
